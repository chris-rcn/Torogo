'use strict';
// Keep only the most extreme |weight| fraction of an hpatterns save file;
// drop the entries closest to zero.  Output is the same int16-quantised
// format, so it loads anywhere the original did.
const fs = require('fs');
const path = require('path');

const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : d; };
const IN   = opt('in');
const OUT  = opt('out');
const KEEP = parseFloat(opt('keep', '0.5'));   // fraction of entries to KEEP

const raw = require(path.resolve(IN));
const { keys, qvals, count, scale, maxStones, maxSize, komi, trainMs, weightsAreEMA } = raw;

// Rank by |q| descending; keep the top KEEP fraction.  Ties at the cut are
// broken by index, so exactly nKeep entries survive.
const order = new Int32Array(count);
for (let i = 0; i < count; i++) order[i] = i;
const abs = new Int32Array(count);
for (let i = 0; i < count; i++) abs[i] = qvals[i] < 0 ? -qvals[i] : qvals[i];
const ord = Array.from(order).sort((a, b) => abs[b] - abs[a]);

const nKeep = Math.round(count * KEEP);
const kKeys = new Int32Array(nKeep);
const kQ    = new Int16Array(nKeep);
for (let i = 0; i < nKeep; i++) { kKeys[i] = keys[ord[i]]; kQ[i] = qvals[ord[i]]; }

const cutAbs = abs[ord[nKeep - 1]];
console.log(`in=${IN}  count=${count}  keep=${KEEP}  ->  ${nKeep} entries`);
console.log(`  |q| cut at ${cutAbs} (weight ${(cutAbs / scale).toExponential(3)}); max |q| ${abs[ord[0]]}`);

const buf = Buffer.alloc(nKeep * 6);
Buffer.from(kKeys.buffer, kKeys.byteOffset, nKeep * 4).copy(buf, 0);
Buffer.from(kQ.buffer,    kQ.byteOffset,    nKeep * 2).copy(buf, nKeep * 4);
const b64 = buf.toString('base64');

const src = [
  "'use strict';",
  '// Auto-generated by train-hpatterns.js — do not edit by hand.',
  '// Weights int16-quantised: weight = qvals[i] / scale.',
  `// Filtered from ${path.basename(IN)}: kept the most extreme ${KEEP} of |weight| (${nKeep}/${count}).`,
  'const hpatternsModel = (() => {',
  `  const count = ${nKeep};`,
  `  const scale = ${scale};`,
  `  const maxStones = ${JSON.stringify(maxStones)};`,
  `  const maxSize = ${maxSize === Infinity ? 'Infinity' : maxSize};`,
  `  const komi = ${komi};`,
  `  const trainMs = ${trainMs};`,
  `  const weightsAreEMA = ${weightsAreEMA};`,
  `  const b64 = '${b64}';`,
  "  const bytes = typeof Buffer !== 'undefined'",
  "    ? Buffer.from(b64, 'base64')",
  "    : Uint8Array.from(atob(b64), c => c.charCodeAt(0));",
  "  const buf = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + count * 6);",
  "  const keys  = new Int32Array(buf, 0, count);",
  "  const qvals = new Int16Array(buf, count * 4, count);",
  "  return { maxStones, maxSize, komi, trainMs, weightsAreEMA, count, scale, keys, qvals };",
  "})();",
  "if (typeof module !== 'undefined') module.exports = hpatternsModel;",
  "else window.hpatternsModel = hpatternsModel;",
].join('\n') + '\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log(`wrote ${OUT}  (${(fs.statSync(OUT).size / 1e6).toFixed(1)} MB)`);
